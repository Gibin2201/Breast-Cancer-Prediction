"""
Inference and Prediction Module for Breast Cancer Classification.
Loads the trained Scikit-learn Pipeline and metadata to generate real-time predictions.
"""

from typing import Dict, Any, Tuple, Optional
from pathlib import Path
import json
import joblib
import numpy as np
import pandas as pd

from config import (
    BEST_MODEL_PATH,
    MODEL_METADATA_PATH,
    FEATURE_NAMES,
    NUMERIC_TO_LABEL,
)
from utils.preprocessing import validate_input_dict


# In-memory cached model and metadata
_CACHED_MODEL = None
_CACHED_METADATA = None


def load_trained_model(force_reload: bool = False):
    """
    Load the trained model pipeline from disk with in-memory caching.
    
    Raises:
        FileNotFoundError: If models/best_model.pkl does not exist.
    """
    global _CACHED_MODEL
    if _CACHED_MODEL is not None and not force_reload:
        return _CACHED_MODEL

    if not BEST_MODEL_PATH.exists():
        raise FileNotFoundError(
            f"Trained model not found at '{BEST_MODEL_PATH}'. "
            "Please run 'python train_model.py' to train and save the model."
        )

    _CACHED_MODEL = joblib.load(BEST_MODEL_PATH)
    return _CACHED_MODEL


def load_model_metadata(force_reload: bool = False) -> Dict[str, Any]:
    """
    Load model metadata and performance metrics from models/model_metadata.json.
    
    Raises:
        FileNotFoundError: If metadata file does not exist.
    """
    global _CACHED_METADATA
    if _CACHED_METADATA is not None and not force_reload:
        return _CACHED_METADATA

    if not MODEL_METADATA_PATH.exists():
        raise FileNotFoundError(
            f"Model metadata not found at '{MODEL_METADATA_PATH}'. "
            "Please train the model first."
        )

    with open(MODEL_METADATA_PATH, "r", encoding="utf-8") as f:
        _CACHED_METADATA = json.load(f)

    return _CACHED_METADATA


def predict_tumor(input_features: Dict[str, Any]) -> Dict[str, Any]:
    """
    Perform tumor diagnosis prediction given 30 numerical input measurements.
    
    Args:
        input_features: Dictionary mapping feature names to numerical values.
        
    Returns:
        Dictionary containing:
        - prediction_code: 0 (Benign) or 1 (Malignant)
        - prediction_label: "Benign" or "Malignant"
        - benign_probability: Float between 0.0 and 1.0
        - malignant_probability: Float between 0.0 and 1.0
        - model_name: Name of the model used
        - confidence: Percentage of dominant class
        - clinical_explanation: Interpretive text
        - disclaimer: Educational/academic disclaimer
    """
    # 1. Validate inputs
    is_valid, err_msg, feature_matrix = validate_input_dict(input_features)
    if not is_valid:
        raise ValueError(f"Input validation error: {err_msg}")

    # 2. Convert to DataFrame with feature names to preserve feature name matching in sklearn
    feature_df = pd.DataFrame(feature_matrix, columns=FEATURE_NAMES)

    # 3. Load pipeline and metadata
    model = load_trained_model()
    metadata = load_model_metadata()

    # 4. Generate prediction
    prediction = int(model.predict(feature_df)[0])
    label = NUMERIC_TO_LABEL.get(prediction, "Unknown")

    # 5. Calculate probabilities
    if hasattr(model, "predict_proba"):
        probabilities = model.predict_proba(feature_df)[0]
        benign_prob = float(probabilities[0])
        malignant_prob = float(probabilities[1])
    elif hasattr(model, "decision_function"):
        score = float(model.decision_function(feature_df)[0])
        malignant_prob = float(1.0 / (1.0 + np.exp(-score)))
        benign_prob = float(1.0 - malignant_prob)
    else:
        malignant_prob = 1.0 if prediction == 1 else 0.0
        benign_prob = 1.0 - malignant_prob

    dominant_prob = max(benign_prob, malignant_prob)

    # 6. Build clinical interpretation
    if prediction == 0:
        explanation = (
            f"The model analyzed all 30 cell nucleus measurements and classified the mass as "
            f"BENIGN (Non-cancerous) with {benign_prob:.1%} model confidence. Features such as mean radius, "
            f"concavity, and perimeter exhibit characteristics typical of non-proliferative, regular cell tissue."
        )
    else:
        explanation = (
            f"The model detected structural irregularity and classified the mass as "
            f"MALIGNANT (Cancerous) with {malignant_prob:.1%} estimated model probability. Elevated values "
            f"in contour concavity, compactness, perimeter, or worst-case variations align with patterns "
            f"consistently correlated with malignant tissue in the WDBC clinical dataset."
        )

    disclaimer = (
        "Educational & Academic Notice: This classification is generated by a machine learning model "
        "trained on the Wisconsin Diagnostic Breast Cancer (WDBC) dataset. The calculated probabilities "
        "represent statistical algorithmic confidence scores and do NOT constitute a medical diagnosis, "
        "biopsy confirmation, or clinical risk evaluation. Always consult licensed medical professionals "
        "for pathological diagnoses."
    )

    return {
        "prediction_code": prediction,
        "prediction_label": label,
        "benign_probability": round(benign_prob, 4),
        "malignant_probability": round(malignant_prob, 4),
        "dominant_confidence": round(dominant_prob * 100, 2),
        "model_name": metadata.get("model_name", "Trained ML Model"),
        "model_accuracy": float(metadata.get("best_model_metrics", {}).get("accuracy", 0.0)),
        "model_version": metadata.get("trained_at", "N/A"),
        "clinical_explanation": explanation,
        "disclaimer": disclaimer,
    }
